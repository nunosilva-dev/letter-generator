package com.nsdev.lettergenerator.model.style;

/** Horizontal paragraph alignment; images also use this value for their enclosing block. */
public enum TextAlign {
    /** Align content with the left edge. */
    LEFT,
    /** Center content between the available edges. */
    CENTER,
    /** Align content with the right edge. */
    RIGHT,
    /** Distribute paragraph text across the available line width. */
    JUSTIFY
}
